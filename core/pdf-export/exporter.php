<?php

namespace MetCraft\Core\PDF_Export;

defined( 'ABSPATH' ) || exit;

/**
 * PDF Export for MetCraft form entries.
 * Generates a PDF document for a single entry.
 */
class Exporter {

	/**
	 * Export a single entry to PDF.
	 *
	 * @param int $entry_id Entry ID.
	 * @return string PDF file path or empty on failure.
	 */
	public static function export( $entry_id ) {
		$entry_id = absint( $entry_id );
		$entry = get_post( $entry_id );

		if ( ! $entry || 'metcraft-entry' !== $entry->post_type ) {
			return '';
		}

		$form_id = (int) get_post_meta( $entry_id, '_metcraft_form_id', true );
		$data    = get_post_meta( $entry_id, '_metcraft_entry_data', true );
		if ( ! is_array( $data ) ) {
			$data = [];
		}

		$pdf_content = self::generate_pdf( $entry, $data, $form_id );

		$upload_dir = wp_upload_dir();
		$filename   = 'metcraft-entry-' . $entry_id . '.pdf';
		$filepath   = $upload_dir['basedir'] . '/metcraft-pdfs/' . $filename;

		if ( ! file_exists( dirname( $filepath ) ) ) {
			wp_mkdir_p( dirname( $filepath ) );
		}

		file_put_contents( $filepath, $pdf_content );

		return $filepath;
	}

	/**
	 * Generate simple HTML-to-PDF content.
	 * Uses dompdf if available, otherwise generates HTML with print styles.
	 *
	 * @param object $entry Entry post object.
	 * @param array $data Entry data.
	 * @param int $form_id Form ID.
	 * @return string
	 */
	private static function generate_pdf( $entry, $data, $form_id ) {
		$form = get_post( $form_id );
		$form_title = $form ? $form->post_title : esc_html__( 'Form Entry', 'metcraft' );

		ob_start();
		?>
		<!DOCTYPE html>
		<html>
		<head>
			<meta charset="utf-8">
			<title><?php echo esc_html( $form_title ); ?> - Entry #<?php echo $entry->ID; ?></title>
			<style>
				body { font-family: 'DejaVu Sans', sans-serif; font-size: 12px; color: #333; }
				.header { border-bottom: 2px solid #3b82f6; padding-bottom: 10px; margin-bottom: 20px; }
				.title { font-size: 20px; font-weight: bold; color: #1f2937; }
				.meta { font-size: 11px; color: #6b7280; margin-bottom: 20px; }
				.table { width: 100%; border-collapse: collapse; }
				.table th { background: #f3f4f6; font-weight: bold; text-align: left; padding: 8px; border: 1px solid #d1d5db; }
				.table td { padding: 8px; border: 1px solid #d1d5db; }
				.footer { margin-top: 30px; font-size: 10px; color: #6b7280; border-top: 1px solid #e5e7eb; padding-top: 10px; }
			</style>
		</head>
		<body>
			<div class="header">
				<div class="title"><?php echo esc_html( $form_title ); ?></div>
				<div class="meta">
					<?php echo esc_html__( 'Entry ID: #', 'metcraft' ) . $entry->ID . ' | ' . esc_html__( 'Submitted: ', 'metcraft' ) . esc_html( $entry->post_modified ); ?>
				</div>
			</div>
			<table class="table">
				<tr><th style="width:30%;"><?php esc_html_e( 'Field', 'metcraft' ); ?></th><th><?php esc_html_e( 'Value', 'metcraft' ); ?></th></tr>
				<?php foreach ( $data as $key => $value ) : ?>
					<tr>
						<td><?php echo esc_html( $key ); ?></td>
						<td><?php echo is_array( $value ) ? esc_html( implode( ', ', $value ) ) : esc_html( $value ); ?></td>
					</tr>
				<?php endforeach; ?>
			</table>
			<div class="footer">
				<?php echo esc_html__( 'Generated by MetCraft', 'metcraft' ); ?>
			</div>
		</body>
		</html>
		<?php
		$html = ob_get_clean();

		// Try to use dompdf if available
		if ( class_exists( '\Dompdf\Dompdf' ) ) {
			$dompdf = new \Dompdf\Dompdf();
			$dompdf->loadHtml( $html );
			$dompdf->setPaper( 'A4', 'portrait' );
			$dompdf->render();
			return $dompdf->output();
		}

		// Return HTML content (will be rendered as PDF by browser if needed)
		return $html;
	}

}
